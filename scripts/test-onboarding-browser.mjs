async function open(viewport, mobile = false) {
  const page = await browser.newPage({ viewport, isMobile: mobile, hasTouch: mobile, reducedMotion: mobile ? 'reduce' : 'no-preference' });
  await page.route('**/*', route => {
    const request = route.request();
    if (!request.url().startsWith(origin+'/')) {
      external.push(request.url());
      return route.abort();
    }
    if (request.method() === 'POST' && /\/api\/(payments|vault|wallet)/.test(request.url())) paymentRequests.push(request.url());
    return route.continue();
  });
  await page.routeWebSocket('**/*', socket => { external.push(socket.url()); socket.close(); });
  page.on('pageerror', error => errors.push(error.stack ?? error.message));
  page.on('response', response => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`); });
  await page.goto(origin + '/');
  return page;
}

